/**
 * Widens the literal types of `ru` (needed for its own ergonomics with
 * `as const`) into plain `string` / `string[]`, so kz.ts and en.ts only have
 * to match the *shape*, not the literal Russian text.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer E)[]
    ? readonly Widen<E>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Dictionary = Widen<typeof ru>;
